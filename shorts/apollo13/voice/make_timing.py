"""Map the current narration onto the picture's story clock, and build the one-word subtitles.

The picture and sound are written in "story frames": frames of the first (62 s) cut, whose word timings are kept in
words_story.json. When the voice is re-made, this maps every real frame to a story frame word by word (piecewise
linear between word starts/ends), so every shot, gag and sound still lands on its word.

python shorts/apollo13/voice/make_timing.py
  -> src/videos/apollo13/timing.ts  (WARP pairs, REAL_FRAMES, CAPS for the subtitles)
  -> shorts/apollo13/voice/warp.json (the same map, for audio/apollo13_sound.py)
"""
import json, math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
FPS, STORY_TOTAL = 30, 1875
old = json.load(open(os.path.join(HERE, "words_story.json")))
new = json.load(open(os.path.join(HERE, "words.json")))
assert len(old) == len(new)

pairs = [(0.0, 0.0)]
for o, n in zip(old, new):
    for no, oo in ((n["start"], o["start"]), (n["end"], o["end"])):
        if no > pairs[-1][0] + 1e-3 and oo > pairs[-1][1] + 1e-3:
            pairs.append((no, oo))
tail = STORY_TOTAL / FPS - old[-1]["end"]                  # same tail after the last word as the story cut
real_total = math.ceil((new[-1]["end"] + tail) * FPS)
pairs.append((real_total / FPS, STORY_TOTAL / FPS))
warp = [[round(a * FPS, 2), round(b * FPS, 2)] for a, b in pairs]
# one story frame per real frame, smoothed over 9 frames so the camera speed never jitters word to word
import numpy as np
xs, ys = np.array([w[0] for w in warp]), np.array([w[1] for w in warp])
raw = np.interp(np.arange(real_total + 1), xs, ys)
k = 4; pad = np.concatenate([raw[0] - (raw[k:0:-1] - raw[0]), raw, raw[-1] + (raw[-1] - raw[-2:-k - 2:-1])])
story = np.convolve(pad, np.ones(2 * k + 1) / (2 * k + 1), mode="valid")[: real_total + 1]
story = np.maximum.accumulate(np.clip(story, 0, STORY_TOTAL))
err = max(abs(np.interp(n["start"] * FPS, np.arange(real_total + 1), story) - o["start"] * FPS) for o, n in zip(old, new))

# subtitles: the script's own spelling and punctuation (double quotes dropped), one word at a time
txt = open(os.path.join(HERE, "script.txt"), encoding="utf8").read()
tokens = [t.replace('"', "") for t in txt.split()]
assert len(tokens) == len(new), (len(tokens), len(new))
for t, w in zip(tokens, new):
    assert re.sub(r"[^a-z']", "", t.lower()) == w["word"].lower(), (t, w["word"])
caps = [{"text": t, "start": w["start"], "end": w["end"]} for t, w in zip(tokens, new)]

ts = ("// generated by shorts/apollo13/voice/make_timing.py: do not edit by hand\n"
      "/** story frame for every real frame: the narration re-timed onto the picture's story clock (smoothed) */\n"
      f"export const STORY: number[] = {json.dumps([round(float(v), 2) for v in story])};\n"
      f"export const REAL_FRAMES = {real_total};\n"
      "/** one-word subtitles (seconds of the real narration) */\n"
      "export const CAPS: { text: string; start: number; end: number }[] = [\n"
      + "".join(f"  {json.dumps(c)},\n" for c in caps) + "];\n")
open(os.path.join(ROOT, "src/videos/apollo13/timing.ts"), "w", encoding="utf8", newline="\n").write(ts)
json.dump({"story": [round(float(v), 3) for v in story], "real_frames": real_total}, open(os.path.join(HERE, "warp.json"), "w"))
print(f"max word offset {err:.2f} f, {len(warp)} warp points, {real_total} real frames ({real_total / FPS:.2f} s), {len(caps)} subtitles")
