"""Shadow tax: one-word subtitles and the film length from the narration word timings.

The picture and sound are written directly on the narration clock (frames = seconds x 30 of voice/words.json),
so unlike Apollo 13 there is no story-clock warp.

python shorts/shadowtax/voice/make_timing.py  -> src/videos/shadowtax/timing.ts (REAL_FRAMES, CAPS)
"""
import json, math, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..", "..")
FPS, TAIL = 30, 0.75  # seconds of picture after the last word
words = json.load(open(os.path.join(HERE, "words.json")))
txt = open(os.path.join(HERE, "script.txt"), encoding="utf8").read()
tokens = [t.replace('"', "") for t in txt.split()]
assert len(tokens) == len(words), (len(tokens), len(words))
for t, w in zip(tokens, words):
    assert re.sub(r"[^a-z']", "", t.lower()) == w["word"].lower(), (t, w["word"])
caps = [{"text": t, "start": w["start"], "end": w["end"]} for t, w in zip(tokens, words)]
real = math.ceil((words[-1]["end"] + TAIL) * FPS)
ts = ("// generated by shorts/shadowtax/voice/make_timing.py: do not edit by hand\n"
      f"export const REAL_FRAMES = {real};\n"
      "/** one-word subtitles (seconds of the narration) */\n"
      "export const CAPS: { text: string; start: number; end: number }[] = [\n"
      + "".join(f"  {json.dumps(c)},\n" for c in caps) + "];\n")
open(os.path.join(ROOT, "src/videos/shadowtax/timing.ts"), "w", encoding="utf8", newline="\n").write(ts)
print(f"{real} frames ({real / FPS:.2f} s), {len(caps)} subtitles")
